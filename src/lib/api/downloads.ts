import { invokeBackend } from "./errors";
import type { MusicAudioQuality } from "./music";
import type { CaptionTrack } from "../../types/video";

export type DownloadMediaKind = "video" | "music" | "audio";
export type DownloadStatus =
  | "queued"
  | "downloading"
  | "paused"
  | "waitingForNetwork"
  | "muxing"
  | "completed"
  | "failed"
  | "cancelled";

/** What the user chose. Stream links are resolved by the backend when the download
 *  runs, so a queued or restarted download never starts with an expired link. */
export interface StartDownloadRequest {
  videoId: string;
  title: string;
  mediaKind: DownloadMediaKind;
  qualityLabel: string;
  destinationDirectory?: string;
  parallel: boolean;
  threads: number;
  video?: VideoSelection;
  music?: MusicSelection;
  /** A subtitle track to save beside a video and play offline. */
  subtitle?: SubtitleChoice;
  thumbnailUrl?: string;
  author?: string;
  durationSeconds?: number;
  collectionDbId?: number;
  /** The stream's loudness, kept with a song so it is normalized offline too. */
  loudnessDb?: number;
  /** What is written into the file besides the title. */
  tags?: DownloadTagsInput;
}

/** Tags the caller knows. Field names match the backend's `DownloadTags`. */
export interface DownloadTagsInput {
  artists?: string[];
  channelId?: string;
  channelName?: string;
  album?: string;
  albumId?: string;
  albumArtist?: string;
  trackNumber?: number;
  trackTotal?: number;
  playlistId?: string;
  /** `YYYY-MM-DD` or a year. */
  releaseDate?: string;
  description?: string;
  viewCount?: number;
  likeCount?: number;
}

export interface VideoSelection {
  /** The exact format; when it is no longer offered the closest one is used. */
  formatId: string;
  height: number | null;
  fps: number | null;
  videoCodec: string;
  container: DownloadContainer;
  /** An audio track's key (a dub); the original when left out. */
  audioTrack?: string;
}

export interface SubtitleChoice {
  languageCode: string;
  autoGenerated: boolean;
}

export interface MusicSelection {
  quality: MusicAudioQuality;
  preferAac: boolean;
}

export interface DownloadStarted {
  id: string;
  filePath: string;
}

export interface DownloadProgress {
  id: string;
  title: string;
  mediaKind: DownloadMediaKind;
  qualityLabel: string;
  filePath: string;
  downloadedBytes: number;
  totalBytes: number | null;
  status: DownloadStatus;
  error: string | null;
  /** Coarse failure category for a `failed` download (e.g. "network", "streaming",
   *  "internal", "download"); null unless the download terminally failed. */
  errorKind: string | null;
  videoId: string | null;
  thumbnailUrl: string | null;
  collectionDbId: number | null;
  artist: string | null;
  /** Speed over the last few seconds, while downloading. */
  bytesPerSecond: number | null;
  etaSeconds: number | null;
}

export type DownloadContainer = "mp4" | "mkv";

export interface DownloadableFormat {
  formatId: string;
  resolution: string;
  width: number | null;
  height: number | null;
  fps: number | null;
  container: DownloadContainer;
  videoCodec: string;
  audioCodec: string;
  videoMimeType: string;
  audioMimeType: string;
  videoBitrate: number | null;
  audioBitrate: number | null;
  videoSizeBytes: number | null;
  audioSizeBytes: number | null;
  estimatedSizeBytes: number | null;
}

export interface DownloadAudioOption {
  key: string;
  label: string;
  languageCode: string | null;
  isDefault: boolean;
  codec: string;
  bitrate: number | null;
  sizeBytes: number | null;
}

export interface CaptionOption {
  languageCode: string;
  label: string;
  isAutoGenerated: boolean;
}

export interface DownloadOptions {
  formats: DownloadableFormat[];
  audioTracks: DownloadAudioOption[];
  captions: CaptionOption[];
}

export function getDownloadFormats(videoId: string): Promise<DownloadOptions> {
  return invokeBackend<DownloadOptions>("get_download_formats", { videoId });
}

export function setDownloadConcurrency(limit: number): Promise<void> {
  return invokeBackend<void>("set_download_concurrency", { limit });
}

export function startDownload(request: StartDownloadRequest): Promise<DownloadStarted> {
  return invokeBackend<DownloadStarted>("start_download", { request });
}

export function cancelDownload(id: string): Promise<boolean> {
  return invokeBackend<boolean>("cancel_download", { id });
}

export function pauseDownload(id: string): Promise<boolean> {
  return invokeBackend<boolean>("pause_download", { id });
}

export function resumeDownload(id: string): Promise<boolean> {
  return invokeBackend<boolean>("resume_download", { id });
}

/** Starts a failed download again from where it stopped. */
export function retryDownload(id: string): Promise<boolean> {
  return invokeBackend<boolean>("retry_download", { id });
}

/** Removes a failed download and its partial files. */
export function discardDownload(id: string): Promise<boolean> {
  return invokeBackend<boolean>("discard_download", { id });
}

/** Resumes downloads an earlier run left unfinished and returns every unfinished one. */
export function restoreDownloads(): Promise<DownloadProgress[]> {
  return invokeBackend<DownloadProgress[]>("restore_downloads");
}

export function getDownloadLogs(id: string): Promise<string[]> {
  return invokeBackend<string[]>("get_download_logs", { id });
}

export interface DownloadRecord {
  id: number;
  videoId: string | null;
  title: string;
  author: string | null;
  mediaKind: DownloadMediaKind;
  filePath: string;
  thumbnailUrl: string | null;
  durationSeconds: number | null;
  qualityLabel: string | null;
  fileSizeBytes: number | null;
  collectionDbId: number | null;
  createdAt: string;
  /** A loopback link to Flow's own copy of the cover; works offline. */
  coverUrl: string | null;
  /** JSON array of the credited artists. */
  artistsJson: string | null;
  album: string | null;
  albumId: string | null;
  releaseDate: string | null;
  description: string | null;
  channelId: string | null;
  container: string | null;
  videoCodec: string | null;
  /** JSON array of `{ title, startSeconds, endSeconds }`. */
  chaptersJson: string | null;
  /** JSON array of SponsorBlock segments, saved when SponsorBlock was on. */
  sponsorblockJson: string | null;
}

export function listDownloads(): Promise<DownloadRecord[]> {
  return invokeBackend<DownloadRecord[]>("list_downloads");
}

export function getDownloadedVideoIds(): Promise<string[]> {
  return invokeBackend<string[]>("get_downloaded_video_ids");
}

export function deleteDownloads(ids: number[]): Promise<void> {
  return invokeBackend<void>("delete_downloads", { ids });
}

export function clearDownloads(): Promise<void> {
  return invokeBackend<void>("clear_downloads");
}

export interface OfflineStreamInfo {
  url: string;
  contentType: string;
  /** Loopback URL for the cover art saved with the download, when present. */
  artworkUrl: string | null;
  /** Lyrics saved with the download, when present. */
  lyrics: string | null;
  /** The loudness recorded when the song was downloaded. */
  loudnessDb: number | null;
  /** Subtitles saved with a video, served from disk. */
  captions: CaptionTrack[];
}

export function getOfflineStream(
  videoId: string,
  mediaKind: DownloadMediaKind,
): Promise<OfflineStreamInfo> {
  return invokeBackend<OfflineStreamInfo>("get_offline_stream", { videoId, mediaKind });
}

export type DownloadCollectionKind = "playlist" | "album";

export interface CreateCollectionRequest {
  collectionId: string;
  kind: DownloadCollectionKind;
  title: string;
  author?: string;
  thumbnailUrl?: string;
  totalCount: number;
  /** The user's video or music download folder, when they chose one. */
  destinationDirectory?: string;
}

export interface CreatedCollection {
  id: number;
  folderPath: string;
  existingVideoIds: string[];
}

export interface DownloadCollectionRecord {
  id: number;
  collectionId: string;
  kind: DownloadCollectionKind;
  title: string;
  author: string | null;
  thumbnailUrl: string | null;
  folderPath: string;
  totalCount: number;
  downloadedCount: number;
  createdAt: string;
  /** The first saved item's stored cover; works offline. */
  coverUrl: string | null;
}

/** Creates (or reuses) a collection folder + record; returns the destination folder. */
export function createDownloadCollection(
  request: CreateCollectionRequest,
): Promise<CreatedCollection> {
  return invokeBackend<CreatedCollection>("create_download_collection", { request });
}

export function listDownloadCollections(): Promise<DownloadCollectionRecord[]> {
  return invokeBackend<DownloadCollectionRecord[]>("list_download_collections");
}

export function deleteDownloadCollections(ids: number[]): Promise<void> {
  return invokeBackend<void>("delete_download_collections", { ids });
}
