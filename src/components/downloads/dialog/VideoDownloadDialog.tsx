import { useMemo } from "react";
import {
  AlignLeft,
  CalendarDays,
  FileVideo2,
  Image as ImageIcon,
  ListVideo,
  AudioLines,
  Film,
  Type,
} from "lucide-react";

import { getString } from "../../../lib/i18n/index";
import { pickFolder } from "../../../lib/dialogs";
import { CODEC_CHOICES, formatBytes, formatDuration, resolutionBadge, type CodecChoice } from "../../../lib/downloadOptions";
import { IS_MACOS_RUNTIME } from "../../../lib/platform";
import { classifyPlayerError } from "../../../lib/playerError";
import { SETTINGS } from "../../../lib/settings/schema";
import { useVideoDownloadDialog, type VideoDownloadMode } from "../../../lib/useVideoDownloadDialog";
import { useAppSettingsStore } from "../../../store/useAppSettingsStore";
import type { VideoSummary } from "../../../types/video";
import { PlayerErrorState } from "../../ui/PlayerErrorState";
import { SegmentedControl } from "../../ui/SegmentedControl";
import { Select } from "../../ui/Select";
import { DialogFooter, DialogFrame, DialogHeader, SectionLabel, SkeletonRows } from "./DownloadDialogShell";

function SavedInFile({ chapters }: { chapters: boolean }) {
  const items = [
    { icon: <ImageIcon size={14} />, label: getString("download_saved_poster") },
    { icon: <Type size={14} />, label: getString("download_saved_title_channel") },
    { icon: <CalendarDays size={14} />, label: getString("download_saved_date") },
    { icon: <AlignLeft size={14} />, label: getString("download_saved_description") },
    ...(chapters ? [{ icon: <ListVideo size={14} />, label: getString("download_saved_chapters") }] : []),
  ];
  return (
    <div className="flex flex-wrap items-center gap-x-3 gap-y-1.5 text-xs text-chrome-neutral-400">
      <SectionLabel>{getString("download_saved_in_file")}</SectionLabel>
      {items.map((item) => (
        <span key={item.label} className="inline-flex items-center gap-1">
          {item.icon}
          {item.label}
        </span>
      ))}
    </div>
  );
}

export function VideoDownloadDialog({ video, onClose }: { video: VideoSummary; onClose: () => void }) {
  const state = useVideoDownloadDialog(video);
  const defaultFolder = useAppSettingsStore(
    (store) => store.values[SETTINGS.DOWNLOAD_LOCATION] || getString("settings_system_default_videos"),
  );
  const musicFolder = useAppSettingsStore(
    (store) => store.values[SETTINGS.MUSIC_DOWNLOAD_LOCATION] || getString("settings_system_default_music"),
  );

  const audioOptions = useMemo(
    () =>
      state.audioTracks
        .filter((track) => track.codec === "AAC")
        .map((track) => ({
          value: track.key,
          label: `${track.label}${track.isDefault ? ` (${getString("download_audio_original")})` : ""}`,
        })),
    [state.audioTracks],
  );
  const subtitleOptions = useMemo(
    () => [
      { value: "", label: getString("download_subtitles_off") },
      ...state.captions.map((caption) => ({
        value: caption.languageCode,
        label: caption.isAutoGenerated
          ? getString("download_subtitle_auto", caption.label)
          : caption.label,
      })),
    ],
    [state.captions],
  );

  const start = async () => {
    if (await state.submit()) onClose();
  };
  const changeFolder = async () => {
    const path = await pickFolder(getString("settings_video_download_folder"));
    if (path) state.setFolder(path);
  };

  const audioMode = state.mode === "audio";
  const extension = audioMode ? "m4a" : state.selected?.container ?? "mp4";
  const failure = state.error && state.rows.length === 0 ? classifyPlayerError(state.error) : null;
  const vp9OnMac = IS_MACOS_RUNTIME && state.codec === "VP9";

  return (
    <DialogFrame onClose={onClose}>
      <DialogHeader
        artwork={video.thumbnailUrl}
        shape="landscape"
        fallbackIcon={<FileVideo2 size={22} />}
        title={video.title}
        subtitle={video.channelName}
        meta={video.publishedText ?? null}
        badge={video.durationSeconds ? formatDuration(video.durationSeconds) : null}
        onClose={onClose}
      />
      <div className="flex min-h-0 flex-col gap-4 overflow-y-auto px-5 pb-1">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <SegmentedControl<VideoDownloadMode>
            label={getString("download_mode")}
            value={state.mode}
            onChange={state.setMode}
            options={[
              { value: "video", label: getString("download_mode_video"), icon: <Film size={15} /> },
              { value: "audio", label: getString("download_mode_audio"), icon: <AudioLines size={15} /> },
            ]}
          />
          {!audioMode ? (
            <div role="radiogroup" aria-label={getString("download_codec")} className="flex flex-wrap gap-1.5">
              {CODEC_CHOICES.filter((choice) => choice === "Auto" || state.availableCodecs.has(choice)).map((choice) => (
                <button
                  key={choice}
                  type="button"
                  role="radio"
                  aria-checked={state.codec === choice}
                  onClick={() => state.setCodec(choice as CodecChoice)}
                  className={`h-7 rounded-full px-3 text-xs font-medium transition-colors duration-200 ease-out ${
                    state.codec === choice
                      ? "bg-chrome-neutral-100 text-chrome-neutral-950"
                      : "bg-surface-container-high text-chrome-neutral-300 hover:bg-surface-container-highest"
                  }`}
                >
                  {choice === "Auto" ? getString("download_codec_auto") : choice}
                </button>
              ))}
            </div>
          ) : null}
        </div>
        {vp9OnMac ? <p className="text-xs text-chrome-neutral-400">{getString("download_vp9_mac_note")}</p> : null}

        {state.loading ? (
          <SkeletonRows />
        ) : failure ? (
          <PlayerErrorState error={failure} variant="compact" onRetry={state.retry} />
        ) : audioMode ? (
          <div className="flex items-center gap-3 rounded-xl border border-chrome-neutral-800 bg-surface-container px-3 py-3 text-sm">
            <span className="h-4 w-4 rounded-full border-[5px] border-[var(--color-primary)]" aria-hidden />
            <span className="font-mono font-medium text-chrome-neutral-100">AAC</span>
            <span className="min-w-0 flex-1 truncate text-chrome-neutral-400">
              {state.originalAudio?.bitrate ? `${Math.round(state.originalAudio.bitrate / 1000)} kbps · ` : ""}
              {getString("download_audio_only_note")}
            </span>
            <span className="font-mono text-xs text-chrome-neutral-400">{formatBytes(state.totalSize) ?? ""}</span>
          </div>
        ) : state.rows.length === 0 ? (
          <p className="text-sm text-chrome-neutral-400">{getString("download_no_adaptive_formats")}</p>
        ) : (
          <div
            role="radiogroup"
            aria-label={getString("download_resolution")}
            className="overflow-hidden rounded-xl border border-chrome-neutral-800"
            onKeyDown={(event) => {
              if (event.key !== "ArrowDown" && event.key !== "ArrowUp") return;
              event.preventDefault();
              const index = state.rows.findIndex((row) => row.formatId === state.selectedId);
              const next = state.rows[index + (event.key === "ArrowDown" ? 1 : -1)];
              if (next) state.setSelectedId(next.formatId);
            }}
          >
            {state.rows.map((row) => {
              const selected = row.formatId === state.selectedId;
              const badge = resolutionBadge(row.height);
              return (
                <button
                  key={row.formatId}
                  type="button"
                  role="radio"
                  aria-checked={selected}
                  tabIndex={selected ? 0 : -1}
                  onClick={() => state.setSelectedId(row.formatId)}
                  onDoubleClick={() => void start()}
                  className={`grid w-full grid-cols-[18px_64px_minmax(0,1fr)_auto] items-center gap-3 border-t border-chrome-neutral-800 px-3 py-2.5 text-left text-sm transition-colors duration-200 ease-out first:border-t-0 ${
                    selected ? "bg-surface-container" : "hover:bg-surface-container-low"
                  }`}
                >
                  <span
                    aria-hidden
                    className={`h-4 w-4 rounded-full ${
                      selected ? "border-[5px] border-[var(--color-primary)]" : "border-[1.5px] border-chrome-neutral-500"
                    }`}
                  />
                  <span className="font-mono font-medium text-chrome-neutral-100">
                    {row.height ? `${row.height}p` : row.resolution}
                  </span>
                  <span className="flex min-w-0 items-center gap-1.5 text-chrome-neutral-400">
                    {badge ? (
                      <span className="rounded-md bg-surface-container-highest px-1.5 py-0.5 font-mono text-[10px] font-semibold text-chrome-neutral-100">
                        {badge}
                      </span>
                    ) : null}
                    <span className="truncate">
                      {row.videoCodec}
                      {row.fps ? ` · ${row.fps} fps` : ""}
                    </span>
                    {row.container === "mkv" ? (
                      <span className="rounded-md border border-chrome-neutral-700 px-1.5 py-0.5 font-mono text-[10px] text-chrome-neutral-300">
                        MKV
                      </span>
                    ) : null}
                  </span>
                  <span className="font-mono text-xs text-chrome-neutral-400">
                    {formatBytes(row.estimatedSizeBytes) ? `≈ ${formatBytes(row.estimatedSizeBytes)}` : ""}
                  </span>
                </button>
              );
            })}
          </div>
        )}

        {!audioMode && !state.loading && state.rows.length > 0 ? (
          <div className="grid gap-2.5 sm:grid-cols-2">
            <label className="grid gap-1.5">
              <SectionLabel>{getString("download_audio_label")}</SectionLabel>
              <Select
                value={state.audioKey ?? ""}
                onChange={state.setAudioKey}
                disabled={audioOptions.length < 2}
                options={audioOptions.length > 0 ? audioOptions : [{ value: "", label: "AAC" }]}
              />
            </label>
            <label className="grid gap-1.5">
              <SectionLabel>{getString("download_subtitles_label")}</SectionLabel>
              <Select
                value={state.subtitle}
                onChange={state.setSubtitle}
                disabled={state.captions.length === 0}
                options={subtitleOptions}
              />
            </label>
          </div>
        ) : null}

        <SavedInFile chapters={!audioMode} />
      </div>
      <DialogFooter
        fileName={state.title}
        extension={extension}
        onRename={state.setTitle}
        folder={state.folder ?? (audioMode ? musicFolder : defaultFolder)}
        onChangeFolder={() => void changeFolder()}
        sizeLabel={formatBytes(state.totalSize)}
        starting={state.starting}
        disabled={state.loading || (!audioMode && !state.selected)}
        onCancel={onClose}
        onSubmit={() => void start()}
      />
      {state.errorMessage && !failure ? (
        <p role="alert" className="px-5 pb-3 text-sm text-chrome-red-300">{state.errorMessage}</p>
      ) : null}
    </DialogFrame>
  );
}
