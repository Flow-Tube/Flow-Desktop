import { act, createElement } from "react";
import { createRoot, type Root } from "react-dom/client";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

const fetchCaptionText = vi.fn();
vi.mock("../../lib/captionText", () => ({ fetchCaptionText: (caption: unknown) => fetchCaptionText(caption) }));
vi.mock("../../lib/diagnostics", () => ({ logToBackend: vi.fn() }));

const { SubtitleOverlay } = await import("./SubtitleOverlay");

const caption = { id: "c", label: "English", languageCode: "en", url: "u", isAutoGenerated: true, isTranslation: false };

describe("SubtitleOverlay when a track doesn't load", () => {
  let host: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    vi.useFakeTimers();
    vi.stubGlobal("ResizeObserver", class {
      observe() {}
      disconnect() {}
    });
    fetchCaptionText.mockReset();
    host = document.createElement("div");
    document.body.appendChild(host);
    root = createRoot(host);
  });

  afterEach(() => {
    act(() => root.unmount());
    host.remove();
    vi.useRealTimers();
    vi.unstubAllGlobals();
  });

  const show = async () => {
    act(() => {
      root.render(
        createElement(SubtitleOverlay, { captions: [caption], selectedCaptionId: "c", currentTime: 2, shouldShowControls: false }),
      );
    });
    await act(async () => {
      await vi.advanceTimersByTimeAsync(4_600);
    });
  };

  it("says so after its retries when the answer holds no lines", async () => {
    fetchCaptionText.mockResolvedValue("WEBVTT\n\n");
    await show();
    expect(fetchCaptionText).toHaveBeenCalledTimes(3);
    expect(host.textContent).toContain("This subtitle track could not be loaded");
  });

  it("shows the line when a retry succeeds", async () => {
    fetchCaptionText
      .mockRejectedValueOnce(new Error("Caption request refused: 429"))
      .mockResolvedValue("WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nHello there\n");
    await show();
    expect(host.textContent).toContain("Hello there");
  });
});
