import { useCallback, useEffect, useMemo } from "react";
import { getCurrentWebview } from "@tauri-apps/api/webview";
import { invokeBackend } from "./api/errors";
import { localCaptionUrl } from "./captionText";
import { isTauriEnv } from "./api/env";
import { pickFile } from "./dialogs";
import { getString } from "./i18n/index";
import { useLocalSubtitleStore, videoSubtitleState, type LocalSubtitleFile } from "../store/useLocalSubtitleStore";
import { useUiStore } from "../store/useUiStore";
import type { CaptionTrack } from "../types/video";
import { parseCaptionCues } from "../components/player/SubtitleOverlay";

export const SUBTITLE_FILE_EXTENSIONS = ["srt", "vtt"];

const localCaption = ({ name, path }: LocalSubtitleFile): CaptionTrack => ({
  id: localCaptionUrl(path),
  label: name,
  languageCode: "",
  url: localCaptionUrl(path),
  isAutoGenerated: false,
});

export const fileNameOf = (path: string) => path.split(/[\\/]/).pop() || path;

export const isSubtitlePath = (path: string) =>
  SUBTITLE_FILE_EXTENSIONS.includes(path.split(".").pop()?.toLowerCase() ?? "");

/** Files added for this video, first, then what the video offers. */
export function useCaptionsWithLocal(videoId: string | null | undefined, captions: CaptionTrack[]): CaptionTrack[] {
  const files = useLocalSubtitleStore((s) => videoSubtitleState(s.videos, videoId).files);
  return useMemo(() => (files.length > 0 ? [...files.map(localCaption), ...captions] : captions), [captions, files]);
}

/** Adds a file only once it has been read and holds cues, so a bad file never becomes a blank track. */
export async function addSubtitleFile(videoId: string, path: string): Promise<boolean> {
  const failed = () => {
    useUiStore.getState().showToast({ variant: "error", message: getString("subtitle_file_unreadable") });
    return false;
  };
  try {
    const text = await invokeBackend<string>("read_subtitle_file", { path });
    if (parseCaptionCues(text, false).length === 0) return failed();
  } catch {
    return failed();
  }
  useLocalSubtitleStore.getState().addFile(videoId, { name: fileNameOf(path), path });
  return true;
}

export function usePickSubtitleFile(videoId: string | null | undefined): () => Promise<void> {
  return useCallback(async () => {
    if (!videoId) return;
    const path = await pickFile(getString("subtitle_file_pick_title"), [
      { name: getString("subtitle_file_type"), extensions: SUBTITLE_FILE_EXTENSIONS },
    ]);
    if (path) await addSubtitleFile(videoId, path);
  }, [videoId]);
}

/** Inside this element, by the top-left-based physical position the webview reports for a drop. */
function dropLandsOn(element: HTMLElement, position: { x: number; y: number }): boolean {
  const scale = window.devicePixelRatio || 1;
  const x = position.x / scale;
  const y = position.y / scale;
  const box = element.getBoundingClientRect();
  return x >= box.left && x <= box.right && y >= box.top && y <= box.bottom;
}

/** A subtitle file dropped on the player is added to the video playing. */
export function useSubtitleFileDrop(
  containerRef: React.RefObject<HTMLElement | null>,
  videoId: string | null | undefined,
): void {
  useEffect(() => {
    if (!videoId) return;
    let cancelled = false;
    let unlisten: (() => void) | null = null;
    void (async () => {
      if (!(await isTauriEnv()) || cancelled) return;
      const stop = await getCurrentWebview().onDragDropEvent(({ payload }) => {
        if (payload.type !== "drop") return;
        const path = payload.paths.find(isSubtitlePath);
        const container = containerRef.current;
        if (path && container && dropLandsOn(container, payload.position)) void addSubtitleFile(videoId, path);
      });
      if (cancelled) stop();
      else unlisten = stop;
    })().catch(() => {});
    return () => {
      cancelled = true;
      unlisten?.();
    };
  }, [containerRef, videoId]);
}
