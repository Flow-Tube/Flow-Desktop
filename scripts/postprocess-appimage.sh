#!/usr/bin/env bash
# Post-process a Tauri AppImage so it uses the host's display and VA-API stack.
#
# Why each step:
# - libwayland-*: the build host's libwayland is older than recent Mesa stacks
#   expect. An AppImage puts its bundled libs first on the loader search path,
#   so the stale copy wins and EGL creation aborts with `EGL_BAD_PARAMETER`
#   (issue #40). They are on the AppImage excludelist for this reason. Tauri CLI
#   2.12's linuxdeploy stopped bundling some of them, so whatever is present is
#   removed and the rest is only logged.
# - libva*: the bundled libva only searches the build distro's driver directory
#   and can't load drivers built for a newer VA-API (issue #74), so hardware
#   decoding never works. The bundled FFmpeg still links it, so it moves to
#   usr/lib/libva-fallback, which the app puts on the loader path only on hosts
#   without a libva of their own (src-tauri/src/appimage.rs).
# - GDK_BACKEND: older linuxdeploy GTK hooks forced X11 for every user; Flow
#   picks its own backend (src-tauri/src/linux_startup.rs), so a hook that
#   forces one again fails the build.
# Usage: postprocess-appimage.sh <path-to.AppImage> <x86_64|aarch64>
# Rewrites the AppImage in place. Any detached .sig must be regenerated by the
# caller, since the bytes change.
set -euo pipefail

appimage="$1"
arch="$2"
case "$arch" in
  x86_64 | aarch64) ;;
  *) echo "unsupported architecture: $arch" >&2; exit 1 ;;
esac
name="$(basename "$appimage")"
echo "Post-processing $appimage ($arch)"

work="$(mktemp -d)"
cp "$appimage" "$work/"
pushd "$work" >/dev/null
chmod +x "./$name"
"./$name" --appimage-extract >/dev/null
root=squashfs-root
fallback="$root/usr/lib/libva-fallback"

# Record the layout in every build log, so the next bundler change is visible
# before anyone has to unpack a release by hand.
echo "::group::AppImage layout"
find "$root/usr/lib" \( -name 'libwayland-*.so*' -o -name 'libva.so*' -o -name 'libva-*.so*' \) -print | sort
ls -1 "$root/apprun-hooks" 2>/dev/null || echo "(no apprun-hooks)"
grep -Hn 'GDK_BACKEND' "$root"/apprun-hooks/*.sh 2>/dev/null || echo "(no hook mentions GDK_BACKEND)"
echo "::endgroup::"

if grep -En '^[[:space:]]*export[[:space:]]+GDK_BACKEND=' "$root"/apprun-hooks/*.sh 2>/dev/null; then
  echo "an AppRun hook forces GDK_BACKEND; Flow must choose its own backend" >&2
  exit 1
fi

mapfile -t wayland < <(find "$root" -name 'libwayland-*.so*')
for lib in "${wayland[@]}"; do
  echo "removing $lib"
  rm -f "$lib"
done
[ "${#wayland[@]}" -gt 0 ] || echo "no bundled libwayland libraries found"

mapfile -t libva < <(find "$root/usr/lib" -path "$fallback" -prune -o \( -name 'libva.so*' -o -name 'libva-*.so*' \) -print)
if [ "${#libva[@]}" -gt 0 ]; then
  mkdir -p "$fallback"
  for lib in "${libva[@]}"; do
    echo "moving $lib to the libva fallback"
    mv "$lib" "$fallback/"
  done
else
  echo "no bundled libva libraries found"
fi

# The fallback only reaches child processes (the app sets LD_LIBRARY_PATH after
# it starts), so the main binary must not need libva, directly or through a
# bundled library.
needed() { readelf -d "$1" 2>/dev/null | sed -n 's/.*(NEEDED).*\[\(.*\)\]/\1/p'; }
declare -A seen=()
queue=()
for bin in "$root"/usr/bin/*; do
  file -b "$bin" | grep -q ELF && queue+=("$bin")
done
while [ "${#queue[@]}" -gt 0 ]; do
  elf="${queue[0]}"
  queue=("${queue[@]:1}")
  while read -r dep; do
    [ -n "$dep" ] && [ -z "${seen[$dep]:-}" ] || continue
    seen[$dep]=1
    case "$dep" in
      libva.so* | libva-*.so*)
        echo "$elf needs $dep, so the main process can't start without the bundled libva" >&2
        exit 1
        ;;
    esac
    path="$(find "$root/usr/lib" -maxdepth 2 -name "$dep" -print -quit)"
    [ -z "$path" ] || queue+=("$path")
  done < <(needed "$elf")
done

for plugin in libgstlibav.so libgstplayback.so libgstvpx.so; do
  find "$root" -name "$plugin" -print -quit | grep -q . \
    || { echo "$plugin missing from the AppImage: GStreamer bundling is broken" >&2; exit 1; }
done

curl -fsSL -o appimagetool.AppImage \
  "https://github.com/AppImage/appimagetool/releases/download/1.9.1/appimagetool-$arch.AppImage"
chmod +x appimagetool.AppImage
ARCH="$arch" ./appimagetool.AppImage --appimage-extract-and-run "$root" "$name"

# Verify the repack before it replaces the original: libs gone or moved, app
# binary kept.
rm -rf "$root"
chmod +x "./$name"
"./$name" --appimage-extract >/dev/null
if find "$root" -name 'libwayland-*.so*' -print | grep .; then
  echo "libwayland still present after repack" >&2
  exit 1
fi
if find "$root/usr/lib" -path "$fallback" -prune -o \( -name 'libva.so*' -o -name 'libva-*.so*' \) -print | grep .; then
  echo "libva still on the default loader path after repack" >&2
  exit 1
fi
test -n "$(ls -A "$root/usr/bin" 2>/dev/null)" \
  || { echo "no binary in repacked AppImage (repack failed?)" >&2; exit 1; }
popd >/dev/null

cp "$work/$name" "$appimage"
rm -rf "$work"
echo "Post-processed and repacked: $appimage"
