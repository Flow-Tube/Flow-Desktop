import { describe, expect, it } from "vitest";
import { NO_PREFERRED_LANGUAGE, selectPreferredCaptionId } from "./playerRuntime";
import type { CaptionTrack } from "../../types/video";

const track = (id: string, languageCode: string, extra: Partial<CaptionTrack> = {}): CaptionTrack => ({
  id,
  label: id,
  languageCode,
  url: id,
  isAutoGenerated: false,
  ...extra,
});

describe("selectPreferredCaptionId", () => {
  it("takes the first track the video offers on No preference, never a machine translation", () => {
    const tracks = [track("t", "de", { isTranslation: true }), track("a", "fr"), track("b", "en")];
    expect(selectPreferredCaptionId(tracks, NO_PREFERRED_LANGUAGE)).toBe("a");
    expect(selectPreferredCaptionId([track("t", "de", { isTranslation: true })], NO_PREFERRED_LANGUAGE)).toBeNull();
  });

  it("still matches a chosen language", () => {
    expect(selectPreferredCaptionId([track("a", "fr"), track("b", "en")], "en")).toBe("b");
  });
});
